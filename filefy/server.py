# -- Push (we send local files TO a peer) ------------------------------------

def _bridge_push_runner(task_id):
    """Background worker: push local files to a connected peer."""
    task = _bridge_get_transfer(task_id)
    if not task:
        return

    peer = _bridge_get_peer(task["peer_id"])
    if not peer:
        _bridge_update_transfer(task_id, status="error", error="Peer not found")
        return

    peer_url = peer["url"]
    auth = {"Authorization": f"Bearer {peer['session_token']}"}
    files = task["files"]
    destination = task["destination"]

    # Pre-compute total size for progress denominator.
    total_size = 0
    for fp in files:
        try:
            if os.path.isfile(fp):
                total_size += os.path.getsize(fp)
        except OSError:
            pass

    _bridge_update_transfer(task_id, status="running", total_size=total_size)

    transferred = 0
    speed_ref_bytes = 0
    speed_ref_time = time.time()

    for file_path in files:
        if not os.path.isfile(file_path):
            continue

        t = _bridge_get_transfer(task_id)
        if t and t.get("cancelled"):
            _bridge_update_transfer(task_id, status="cancelled", speed=0)
            return

        filename = os.path.basename(file_path)
        _bridge_update_transfer(task_id, current_file=filename)

        try:
            file_size = os.path.getsize(file_path)
        except OSError:
            continue

        # 1. Init remote upload session.
        try:
            resp = requests.post(
                f"{peer_url}/api/bridge/receive-init",
                json={"filename": filename, "path": destination, "size": file_size},
                headers=auth,
                timeout=(10, 30),
            )
        except requests.RequestException as exc:
            _bridge_update_transfer(
                task_id, status="error", error=f"Init failed: {exc}", speed=0
            )
            return

        if not resp.ok:
            try:
                err = resp.json().get("error", f"HTTP {resp.status_code}")
            except Exception:
                err = f"HTTP {resp.status_code}"
            _bridge_update_transfer(
                task_id, status="error", error=f"Init failed: {err}", speed=0
            )
            return

        upload_id = resp.json().get("upload_id", "")

        # 2. Stream chunks.
        try:
            with open(file_path, "rb") as fh:
                offset = 0
                while offset < file_size:
                    t = _bridge_get_transfer(task_id)
                    if t and t.get("cancelled"):
                        try:
                            requests.delete(
                                f"{peer_url}/api/upload-cancel/{upload_id}",
                                headers=auth,
                                timeout=10,
                            )
                        except Exception:
                            pass
                        _bridge_update_transfer(task_id, status="cancelled", speed=0)
                        return

                    chunk = fh.read(BRIDGE_CHUNK_SIZE)
                    if not chunk:
                        break
                    end_byte = offset + len(chunk) - 1
                    chunk_headers = {
                        **auth,
                        "Content-Range": f"bytes {offset}-{end_byte}/{file_size}",
                    }
                    try:
                        resp = requests.put(
                            f"{peer_url}/api/bridge/receive-chunk/{upload_id}",
                            data=chunk,
                            headers=chunk_headers,
                            timeout=(10, 120),
                        )
                    except requests.RequestException as exc:
                        _bridge_update_transfer(
                            task_id, status="error",
                            error=f"Chunk upload failed: {exc}", speed=0
                        )
                        return

                    if not resp.ok:
                        _bridge_update_transfer(
                            task_id, status="error",
                            error=f"Chunk rejected: HTTP {resp.status_code}", speed=0
                        )
                        return

                    offset += len(chunk)
                    transferred += len(chunk)

                    now = time.time()
                    elapsed = now - speed_ref_time
                    if elapsed >= 0.5:
                        speed = (transferred - speed_ref_bytes) / elapsed
                        speed_ref_bytes = transferred
                        speed_ref_time = now
                        progress = (
                            min(PROGRESS_CAP_BEFORE_COMPLETE, transferred / total_size * 100)
                            if total_size > 0 else 0
                        )
                        _bridge_update_transfer(
                            task_id, transferred=transferred,
                            progress=progress, speed=speed
                        )
        except OSError as exc:
            _bridge_update_transfer(
                task_id, status="error", error=str(exc), speed=0
            )
            return

        # 3. Finalise.
        try:
            resp = requests.post(
                f"{peer_url}/api/bridge/receive-complete/{upload_id}",
                headers=auth,
                timeout=(10, 30),
            )
        except requests.RequestException as exc:
            _bridge_update_transfer(
                task_id, status="error", error=f"Complete failed: {exc}", speed=0
            )
            return

        if not resp.ok:
            _bridge_update_transfer(
                task_id, status="error",
                error=f"Complete failed: HTTP {resp.status_code}", speed=0
            )
            return

    _bridge_update_transfer(
        task_id,
        status="completed",
        progress=100.0,
        speed=0,
        transferred=transferred,
        current_file="",
    )


@app.route("/api/bridge/push", methods=["POST"])
def bridge_push():
    """Push local files to a connected peer server.

    Body (JSON)::

        {
          "peer_id":     "<uuid>",
          "files":       ["/abs/local/path/file1", ...],
          "destination": "/remote/dest/dir"
        }

    Runs in a background thread; returns a ``task_id`` immediately.
    """
    data = request.get_json(silent=True) or {}
    peer_id = data.get("peer_id", "")
    files = data.get("files") or []
    destination = data.get("destination") or ""

    peer = _bridge_get_peer(peer_id)
    if not peer:
        return jsonify({"error": "Peer not found"}), 404

    if not files or not isinstance(files, list):
        return jsonify({"error": "files list is required"}), 400

    safe_files = []
    for f in files:
        if not isinstance(f, str):
            continue
        safe = get_safe_path(f)
        if not os.path.exists(safe):
            return jsonify({"error": "One or more source files were not found"}), 404
        if not os.path.isfile(safe):
            return jsonify({"error": "Only files can be pushed. Compress directories first."}), 400
        safe_files.append(safe)

    if not safe_files:
        return jsonify({"error": "No valid files provided"}), 400

    task_id = str(uuid.uuid4())
    task = {
        "id": task_id,
        "kind": "bridge-push",
        "peer_id": peer_id,
        "peer_name": peer["name"],
        "files": safe_files,
        "destination": destination,
        "status": "pending",
        "progress": 0.0,
        "transferred": 0,
        "total_size": 0,
        "current_file": "",
        "speed": 0,
        "error": None,
        "cancelled": False,
        "created_at": time.time(),
    }
    with _bridge_transfers_lock:
        _bridge_transfers[task_id] = task

    thread = threading.Thread(
        target=_bridge_push_runner, args=(task_id,), daemon=True
    )
    thread.start()
    return jsonify({"task_id": task_id, "message": f"Push started for {len(safe_files)} file(s)"})


# -- Pull (we fetch files FROM a peer) ----------------------------------------

def _bridge_pull_runner(task_id):
    """Background worker: pull remote files from a connected peer."""
    task = _bridge_get_transfer(task_id)
    if not task:
        return

    peer = _bridge_get_peer(task["peer_id"])
    if not peer:
        _bridge_update_transfer(task_id, status="error", error="Peer not found")
        return

    peer_url = peer["url"]
    auth = {"Authorization": f"Bearer {peer['session_token']}"}
    remote_files = task["files"]
    safe_dest = task["destination"]

    _bridge_update_transfer(task_id, status="running")

    transferred = 0
    total_size = 0
    speed_ref_bytes = 0
    speed_ref_time = time.time()

    for remote_path in remote_files:
        t = _bridge_get_transfer(task_id)
        if t and t.get("cancelled"):
            _bridge_update_transfer(task_id, status="cancelled", speed=0)
            return

        filename = os.path.basename(remote_path) or "file"
        _bridge_update_transfer(task_id, current_file=filename)

        try:
            resp = requests.get(
                f"{peer_url}/api/bridge/file",
                params={"path": remote_path},
                headers=auth,
                timeout=(10, 60),
                stream=True,
            )
        except requests.RequestException as exc:
            _bridge_update_transfer(
                task_id, status="error", error=f"Download error: {exc}", speed=0
            )
            return

        if not resp.ok:
            _bridge_update_transfer(
                task_id, status="error",
                error=f"Remote error: HTTP {resp.status_code}", speed=0
            )
            return

        file_size = int(resp.headers.get("Content-Length") or 0)
        total_size += file_size
        _bridge_update_transfer(task_id, total_size=total_size)

        dest_path = reserve_download_path(safe_dest, filename)
        try:
            with open(dest_path, "wb") as fh:
                for chunk in resp.iter_content(chunk_size=BRIDGE_CHUNK_SIZE):
                    t = _bridge_get_transfer(task_id)
                    if t and t.get("cancelled"):
                        _bridge_update_transfer(task_id, status="cancelled", speed=0)
                        cleanup_download_files(dest_path)
                        return

                    fh.write(chunk)
                    transferred += len(chunk)

                    now = time.time()
                    elapsed = now - speed_ref_time
                    if elapsed >= 0.5:
                        speed = (transferred - speed_ref_bytes) / elapsed
                        speed_ref_bytes = transferred
                        speed_ref_time = now
                        cur_total = (_bridge_get_transfer(task_id) or {}).get("total_size") or 0
                        progress = (
                            min(PROGRESS_CAP_BEFORE_COMPLETE, transferred / cur_total * 100)
                            if cur_total > 0 else 0
                        )
                        _bridge_update_transfer(
                            task_id, transferred=transferred,
                            progress=progress, speed=speed
                        )
        except OSError as exc:
            cleanup_download_files(dest_path)
            _bridge_update_transfer(
                task_id, status="error", error=str(exc), speed=0
            )
            return

    _bridge_update_transfer(
        task_id,
        status="completed",
        progress=100.0,
        speed=0,
        transferred=transferred,
        current_file="",
    )


