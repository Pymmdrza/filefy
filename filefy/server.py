def get_safe_path(path):
    """Ensure the path is within the allowed directory"""
    if not path:
        return BASE_DIR

    # Decode URL-encoded path
    path = unquote(path)

    # Expand ~ to home directory
    if path.startswith("~"):
        path = os.path.expanduser(path)

    # Handle absolute and relative paths
    if path.startswith("/"):
        full_path = os.path.abspath(path)
    else:
        full_path = os.path.abspath(os.path.join(BASE_DIR, path))

    return full_path


def get_file_info(file_path):
    """Get detailed information about a file or directory"""
    try:
        stat = os.stat(file_path)
        is_dir = os.path.isdir(file_path)

        return {
            "name": os.path.basename(file_path),
            "path": file_path,
            "is_dir": is_dir,
            "size": 0 if is_dir else stat.st_size,
            "size_formatted": format_size(stat.st_size) if not is_dir else "-",
            "modified": datetime.fromtimestamp(stat.st_mtime).strftime(
                "%Y-%m-%d %H:%M:%S"
            ),
            "created": datetime.fromtimestamp(stat.st_ctime).strftime(
                "%Y-%m-%d %H:%M:%S"
            ),
            "extension": os.path.splitext(file_path)[1].lower() if not is_dir else "",
            "permissions": oct(stat.st_mode)[-3:],
            "icon": get_file_icon(file_path, is_dir),
        }
    except (OSError, PermissionError):
        return None


def get_dir_size(path):
    """Calculate total size of a directory"""
    total = 0
    try:
        for entry in os.scandir(path):
            if entry.is_file():
                total += entry.stat().st_size
            elif entry.is_dir():
                total += get_dir_size(entry.path)
    except PermissionError:
        pass
    return total


def format_size(size):
    """Format file size in human-readable format"""
    for unit in ["B", "KB", "MB", "GB", "TB"]:
        if size < 1024.0:
            return f"{size:.2f} {unit}"
        size /= 1024.0
    return f"{size:.2f} PB"


